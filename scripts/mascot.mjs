// Generates César's pixel mascot (src/components/Mascot.astro and public/favicon.svg)
// from a 16x16 ASCII grid, so the art stays easy to tweak.
import { writeFileSync } from 'node:fs';

const art = [
  '....H.HH.HH.H...',
  '...HHHHHHHHHH...',
  '..HHHHHHHHHHHH..',
  '..HHHHHHHHHHHH..',
  '..HSSSSSSSSSSH..',
  '..SSSSSSSSSSSS..',
  '..GGGGGGGGGGGG..',
  '..GLELGSSGLELG..',
  '..GLLLGSSGLLLG..',
  '..SGGGSSSSGGGS..',
  '..SSSSSSSSSSSS..',
  '..SSSMWWWWMSSS..',
  '...SSSMMMMSSS...',
  '....SSSSSSSS....',
  '..BBBbSSSSbBBB..',
  '.BBBBBbbbbBBBBB.',
];

const colors = {
  H: '#17171c', // curly hair
  S: '#e7b18c', // skin
  G: '#2b3140', // glasses frame
  L: '#d7e6ff', // lens
  E: '#17171c', // eyes
  M: '#8f2f2f', // mouth
  W: '#ffffff', // teeth
  B: '#2a2a33', // shirt
  b: '#4a4a57', // collar
};

let rects = '';
art.forEach((row, y) => {
  [...row].forEach((ch, x) => {
    if (ch === '.') return;
    const cls = ch === 'E' ? ' class="eye"' : '';
    rects += `<rect x="${x}" y="${y}" width="1.02" height="1.02" fill="${colors[ch]}"${cls}/>`;
  });
});

const svg = (extra = '') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges"${extra}>${rects}</svg>`;

writeFileSync(
  'src/components/Mascot.astro',
  `---\n// Generated by scripts/mascot.mjs. Edit the grid there, then run: node scripts/mascot.mjs\ninterface Props { class?: string }\nconst { class: className } = Astro.props;\n---\n\n<span class:list={['mascot', className]} aria-hidden="true">${svg()}</span>\n`,
);

writeFileSync(
  'public/favicon.svg',
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-2 -2 20 20" shape-rendering="crispEdges"><rect x="-2" y="-2" width="20" height="20" rx="4" fill="#f7f7f8"/>${rects}</svg>`,
);
console.log('mascot generated');
